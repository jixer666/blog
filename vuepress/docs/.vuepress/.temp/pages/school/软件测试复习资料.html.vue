## 1.软件测试层次（P10）
<ul>
<li><strong>单元测试</strong>：包括代码评审（静态测试）和运行单元程序进行测试（动态测试）。单元测试一 般由开发人员完成。</li>
<li><strong>集成测试</strong>：也称组装测试、联合测试、子系统测试，在单元测试的基础上，将模块按照设 计要求组装起来同时进行测试，主要目标是发现与接口有关的模块之间问题。</li>
<li><strong>系统测试</strong>：是将软件放在整个计算机环境下，包括软硬件平台、某些支持软件、数据和人 员等，在实际运行环境下进行一系列的测试，包括恢复测试、安全测试、强度测试和性能 测试等。</li>
<li><strong>验收测试</strong>：是指在软件产品完成了系统测试之后、产品发布之前所进行的软件测试活动。 它是技术测试的最后一个阶段，也称为交付测试，确保所开发的软件产品是否符合用户预 期的各项要求。验收测试的重要特征就是用户参与。</li>
</ul>
