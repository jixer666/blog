<h2 id="_14-测试风险分类-p267" tabindex="-1"><a class="header-anchor" href="#_14-测试风险分类-p267"><span>14.测试风险分类（P267）</span></a></h2>
<p>测试风险很多，但可以分为两类——<strong>测试对象剖面的风险</strong>和<strong>测试操作剖面的风险</strong>。
（1）测试对象剖面的风险，即测试对象比较复杂，测试的广度和深度都不够。例如，系统所涉及的业务处理复杂、测试范围没有说明清楚、用户的各种使用场景(scenario)未被捕捉到、某些例外的测试用例没有想到等。
（2）测试操作剖面的风险，主要指测试操作过程中存在的各种风险，例如测试环境和真实运行环境差异较大、测试流程不够完善导致测试执行难以控制、回归测试中以风险换时间的策略等。</p>
