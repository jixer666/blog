<h2 id="_9-单元测试中测试用例设计覆盖方法-p86" tabindex="-1"><a class="header-anchor" href="#_9-单元测试中测试用例设计覆盖方法-p86"><span>9.单元测试中测试用例设计覆盖方法（P86）</span></a></h2>
<ul>
<li><strong>语句覆盖</strong>：使得程序中每一条可执行语句至少被执行一次。</li>
<li><strong>分支覆盖（判定覆盖）</strong>：使得程序中每一个分支都至少被执行一次。（要求判定表达式的值的真假分支都被执行）</li>
<li><strong>条件覆盖</strong>：程序中每一个条件至少有一次被满足。（要求判定表达式的每个条件的值的真假分支都被执行）</li>
<li><strong>路径覆盖</strong>：对程序模块的所有独立的基本路径至少要测试一次。</li>
</ul>
<blockquote>
<p>额外内容：</p>
<p>条件覆盖跟判定覆盖的区别：
举个例子：
判定表达式：a &gt; 3 and b &gt; 0
用判定覆盖设计的测试用例:
a: true, b: true
a: false,b: false
-&gt; a = 5, b = 1 (判定表达式的值为“真”)
-&gt; a = 0, b = 1 (判定表达式的值为“假”)
注意：这里并不需要管b的取值，就已经满足判定覆盖的条件了。
用条件覆盖设计的测试用例：
a: true, b: false
a: ture, b: true
a: alse, b: false
a: false, b: true
-&gt; a = 5, b = 1 (条件a &gt; 3为真， 条件b &gt; 0为真)
-&gt; a = 5, b = -1 (条件a &gt; 3为真， 条件b &gt; 0为假)
-&gt; a = -5, b = 1 (条件a &gt; 3为假， 条件b &gt; 0为真)
-&gt; a = -5, b = -1(条件a &gt; 3为假， 条件b &gt; 0为假)</p>
</blockquote>
<h2 id="_10-移动应用-app特有的测试-p196" tabindex="-1"><a class="header-anchor" href="#_10-移动应用-app特有的测试-p196"><span>10.移动应用 APP特有的测试（P196）</span></a></h2>
<p>针对移动App应用测试,除了针对代码的单元测试、系统功能测试之外,侧重考虑下列测试。</p>
<ul>
<li>兼容性测试，包括硬件差异、操作系统版本等。</li>
<li>交互性测试，不同的操作同时发生，例如微信操作时电话来了。</li>
<li>用户体验测试，即用户易用性测试,如横竖切换、触摸、多指触摸、缩放、分页和导航等操作灵活性、局限性。</li>
<li>耗电量测试，可以通过仪器来检测,也可以通过判断计算效率是否是最优的来进行评估。</li>
<li><strong>网络流量测试</strong>，数据传输是否压缩,是否只传输必要的信息?</li>
<li><strong>网络连接</strong>，在低速无线连接、不同网络间的切换情况下，软件容错性、稳定性如何?在无网络的情况下，App支持离线操作吗?</li>
<li>性能测试，在移动设备端，主要通过内存、进程占有CPU资源等分析来完成任务。</li>
<li>稳定性测试，移动App闪退问题比较多，如何更好地发现App应用崩溃问题？</li>
</ul>
<h2 id="_11-缺陷优先级-p235" tabindex="-1"><a class="header-anchor" href="#_11-缺陷优先级-p235"><span>11.缺陷优先级（P235）</span></a></h2>
<ul>
<li>立即解决（P1级）：缺陷导致系统几乎不能运行、使用，或者严重妨碍测试的执行，需立即修正、尽快修正</li>
<li>高优先级（P2级）：缺陷严重，影响测试，需要优先考虑修正。例如不超过24小时修正</li>
<li>正常排队（P3级）：缺陷需要修正，但可以正常排队等待修正</li>
<li>低优先级（P4级）：缺陷可以在开发人有时间的时候被修正，如果没有时间，可以不修正</li>
</ul>
<blockquote>
<p>额外内容：软件缺陷<strong>严重性</strong></p>
<ul>
<li>0级（致命）：最严重等级,缺陷导致系统任何一个主要功能完全丧失、用户数据受到破坏、系统崩溃悬挂、死机等</li>
<li>1级（严重）：系统的主要功能部分丧失，数据不能完整保存，系统的次要功能完全丧失，系统所提供的功能或服务受到明显的影响</li>
<li>2级（一般）：系统的次要功能没有完全实现，但不影响用户的正常使用。例如提示信息不太准确;或用户界面差、操作时间稍长等问题</li>
<li>3级（较小）：操作者不方便或遇到麻烦，但不影响功能的操作和执行,如字体不美观、按钮大小不是很合适、文字排列不对齐等一些小问题</li>
</ul>
</blockquote>
<h2 id="_12-缺陷分析的方法-p242" tabindex="-1"><a class="header-anchor" href="#_12-缺陷分析的方法-p242"><span>12.缺陷分析的方法（P242）</span></a></h2>
<p>从缺陷的层次看，可以分为：</p>
<ul>
<li>宏观分析：根据缺陷的总体数据分析，可以了解整体的测试效率、开发人员修正缺陷的效率、测试是否能达到预期的目标。</li>
<li>微观分析：发现测试的漏洞，评估具体模块的代码质量以及具体缺陷描述中所存在的问题。</li>
</ul>
<blockquote>
<p>额外内容：最常用的缺陷分析方法有4种，分别是<strong>缺陷分布报告、缺陷趋势报告、缺陷年龄报告、测试结果进度报告</strong>。</p>
</blockquote>
