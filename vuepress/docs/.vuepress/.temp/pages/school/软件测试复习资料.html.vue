<h2 id="_7-静态测试-动态测试-p9" tabindex="-1"><a class="header-anchor" href="#_7-静态测试-动态测试-p9"><span>7.静态测试，动态测试（P9）</span></a></h2>
<ul>
<li>动态测试是通过运行程序来发现软件系统中的问题。这种测试是在程序运行过程中将缺陷发现出来,具有动态性,所以称为动态测试。</li>
<li>静态测试主要活动是评审，即通过对需求、设计、配置、程序和其他各类文档的审查来检验相应内容是否满足用户的需求。不需要运行程序，测试对象属于静态的。</li>
</ul>
<blockquote>
<p>额外内容：
黑盒测试有可能是动态测试（运行程序，看输入输出），也有可能是静态测试（不运行，只看界面）
白盒测试有可能是动态测试（运行程序并分析代码结构），也有可能是静态测试（不运行程序，只静态察看代码）
动态测试有可能是黑盒测试（运行，只看输入输出），也有可能是白盒测试 （运行并分析代码结构）
静态测试有可能是黑盒测试（不运行，只察看界面），也有可能是白盒测试（不运行，只察看代码）</p>
</blockquote>
<h2 id="_8-驱动程序、桩程序-p85" tabindex="-1"><a class="header-anchor" href="#_8-驱动程序、桩程序-p85"><span>8.驱动程序、桩程序（P85）</span></a></h2>
<ul>
<li>
<p>**驱动程序（driver )，对底层或子层模块进行(单元或集成）测试时所编制的调用被测模块的程序，用以模拟被测模块的上级模块。**驱动模块在集成测试中接受测试数据，调用被测模块,并把相关的数据传送给被测模块，然后获得测试结果。当被测模块是底层模块时，如图5-3中的模块E、F、C和G,需要创建驱动程序。</p>
</li>
<li>
<p>**桩程序（stub）,也有人称为存根程序，对顶层或上层模块进行测试时，所编制的替代下层模块的程序,用以模拟被测模块工作过程中所调用的模块。**桩模块相当于电路中的短路器，使上层模块不需要调用真实模块，就能获得所需要的参数、返回值等。桩模块由被测试模块调用，其内部尽量简单，例如，按照简单条件进行判断,给出返回值，使被测试模块得到它需要得到的值。当被测模块是上层模块时,如图5-3中的模块A，就需要建立桩程序。</p>
</li>
</ul>
