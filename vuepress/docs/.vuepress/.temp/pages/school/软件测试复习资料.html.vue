<h2 id="_23-软件质量概念" tabindex="-1"><a class="header-anchor" href="#_23-软件质量概念"><span>23.软件质量概念</span></a></h2>
<p>概括地说，软件质量就是“软件与明确地和隐含地定义的需求相一致的程度”。更具体地说，软件质量是软件与明确地叙述的功能和性能需求、文档中明确描述的开发标准以及任何专业开发的软件产品都应该具有的隐含特征相一致的程度。从管理角度对软件质量进行度量，可将影响软件质量的主要因素划分为三组，分别反应用户在使用软件产品时的三种不同倾向或观点：产品运行(正确性、健壮性、效率、完整性、可用性、风险);产品修改(可理解性、可维修性、灵活性、可测试性);产品转移(可移植性、可再用性、互运行性)。</p>
<blockquote>
<p>软件质量特性是指软件的功能性、可靠性、易用性、效率、可维护性、可移植性</p>
</blockquote>
<h2 id="_24-软件测试中的v-v模型-p8" tabindex="-1"><a class="header-anchor" href="#_24-软件测试中的v-v模型-p8"><span>24.软件测试中的V&amp;V模型（P8）</span></a></h2>
<p>软件测试中的V&amp;V模型分别代表<strong>验证</strong>和<strong>有效性确认</strong></p>
<p>验证：是否正确地构造了软件？即是否正确地做事，验证开发过程是否遵守已定义好的内容。验证产品满足规格设计说明书的一致性。</p>
<p>有效性确认：是否构造了正是用户所需要的软件？即是否正在做正确的事。验证产品所实现的功能是否满足用户的需求。</p>
