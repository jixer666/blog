<h2 id="_16-集成测试策略-p97" tabindex="-1"><a class="header-anchor" href="#_16-集成测试策略-p97"><span>16.集成测试策略（P97）</span></a></h2>
<ul>
<li>自顶向下集成策略：从主控模块开始，沿着软件的控制层次向下移动，从而逐渐把各个模块结合起来。在组装过程中，可以使用深度优先或宽度优先的策略。</li>
<li>自底向上集成策略：从底层模块开始（即在软件结构最底层的模块）开始，向上推进，不 断进行集成测试的方法。</li>
<li>混合策略：对软件结构中较上层，使用的是&quot;自顶向下&quot;法；对软件结构中较下层，使用 的是&quot;自底向上&quot;法，两者相结合。</li>
</ul>
<h2 id="_17-负载测试-压力测试-性能测试-p157" tabindex="-1"><a class="header-anchor" href="#_17-负载测试-压力测试-性能测试-p157"><span>17.负载测试，压力测试，性能测试（P157）</span></a></h2>
<ul>
<li>**负载测试是通过模拟实际软件系统所承受的负载条件、改变系统负载大小和负载方式来发现系统中所存在的问题。**例如，逐渐增加模拟用户的数量来观察系统的响应时间和数据吞吐量、系统占用的资源（如CPU、内存）等，以检验系统的行为和特性，发现系统可能存在的性能瓶颈、内存泄漏、不能实时回步寺问题。贝我测A文地以为性能测试、压力测试所采用。</li>
<li>**压力测试是在强负载情况下（如大数据量、大量并发用户连接等）对稳定性进行测试，查看应用系统在峰值（瞬间使用高峰)使用情况下的行为表现;更有效地发现系统稳定性的隐患和系统在负载峰值的条件下功能隐患等，确认系统是否具有良好的容错能力和可恢复能力。**压力测试分为高负载下的长时间（如24小时以上)的稳定性压力测试和极限负载情况下导致系统崩溃的破坏性压力测试。</li>
<li>**性能测试是为获取或验证系统性能指标而进行的测试。**性能测试，目的明确，事先有明确的性能指标，并要求在严格的测试环境和所定义的测试负载情况下进行,获得在不同的负载情况下的性能指标数据。性能测试使用负载测试的技术、工具以及用不同的负载水平来度量性能指标和建立性能基准。</li>
</ul>
