<h2 id="_28-软件测试中控制风险的对策-p268" tabindex="-1"><a class="header-anchor" href="#_28-软件测试中控制风险的对策-p268"><span>28.软件测试中控制风险的对策（P268）</span></a></h2>
<ul>
<li>消除执行风险：通过系统复审、测试人员之间互审、测试人员在不同的测试模块上相互调换、自动化测试和抽查等方法,及时发现问题，并产生震慑作用，确保测试用例被100%执行。</li>
<li>降低进度风险：进行测试资源、时间等估算时,要留有余地,增加10%的空间，以降低测试资源可能不足的风险。</li>
<li>减少人员风险：对每个关键性技术人员培养后备人员，做好不同领域知识的培训，从而确保人员一旦离开公司,项目不会受到严重影响。</li>
</ul>
