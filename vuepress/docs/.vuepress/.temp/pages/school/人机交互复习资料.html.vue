<h2 id="移动界面设计的设计原则" tabindex="-1"><a class="header-anchor" href="#移动界面设计的设计原则"><span><strong>移动界面设计的设计原则</strong>：</span></a></h2>
<p>（1）简单直观。受资源限制，移动界面的开发不能简单地看成网页的缩小版，且为兼顾简便性，其设计应该尽可能的简单；</p>
<p>（2）个性化设计。充分利用移动设备的复杂多样性以及设备间的性能差异，做到个性化设计；</p>
<p>（3）易于检索。避免嵌套过深的多级菜单，缩减不必要的功能，以满足用户的目标需求为准，尽量减少用户进行信息访问时的步骤；</p>
<p>（4）界面风格一致性。在设计过程中，应当检查每个布局和每个显示保证其一致性，不必要的差异会让用户感到不习惯；</p>
<p>（5）避免不必要的文本输入。尽量使用户避免不必要的文本信息的输入，而采用列表或者模糊查询，降低用户进行文本输入的麻烦。</p>
