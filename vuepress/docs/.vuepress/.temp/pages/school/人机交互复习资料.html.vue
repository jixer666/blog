<h2 id="web-界面设计原则" tabindex="-1"><a class="header-anchor" href="#web-界面设计原则"><span><strong>Web 界面设计原则</strong></span></a></h2>
<ol>
<li>以用户为中心。它要求把用户放在第一位，设计时既要考虑用户的共性，同时也要考虑他们之间的差异性。</li>
<li>一致性。必须考虑内容和形式的一致性。内容指网站显示的信息、数据等；形式指的是界面的设计版式、构图、布局等以及他们呈现出的风格特点。</li>
<li>简洁与明确。尽量减少浏览层次。</li>
<li>体现特色。设计者应清楚了解网站背景、所体现主体和服务对象的基本情况，选择合适的表现手法展示关键信息和特色内容，形成独特鲜明的风格。</li>
<li>兼容不同的浏览器。在 web 界面设计时，应该根据当时用户浏览器分布情况决定设计所面向的浏览器类别和版本，以保证其正常工作。</li>
</ol>
